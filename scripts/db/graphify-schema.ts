/**
 * Turns a `pg_dump --schema-only` of the public schema into simple DDL that
 * graphify's tree-sitter SQL parser can read, and writes it where every
 * `graphify update .` picks it up (graphify-out/memory/ is always scanned).
 *
 * Why not feed graphify the migrations or the raw dump:
 * - The 848 migrations replay history: dropped tables come back and ~60% of
 *   the live schema is missed because the parser stops at the first statement
 *   it cannot read.
 * - The raw dump fails the same way (8 nodes out of ~650 objects).
 * - Node ids include the file stem, so all tables must sit in one file for
 *   FK edges to join to the table nodes.
 *
 * Usage:
 *   tsx scripts/db/graphify-schema.ts                # pg_dump via POSTGRES_URL_NON_POOLING
 *   tsx scripts/db/graphify-schema.ts --dump <file>  # convert an existing dump
 * Set PG_DUMP to a pg_dump at least as new as the server (e.g. postgresql@15).
 */
import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

export const GRAPH_SCHEMA_PATH = 'graphify-out/memory/schema/public_schema.sql';

export interface GraphDdl {
  ddl: string;
  counts: Record<'table' | 'view' | 'function' | 'fk' | 'trigger' | 'external', number>;
}

const IDENT = '"?[\\w]+"?';

function bare(text: string): string {
  return text.replace(/\bpublic\./g, '').replace(/"/g, '');
}

function qualified(schema: string, name: string): string {
  return schema === 'public' ? bare(name) : `${schema}_${bare(name)}`;
}

export function convertDumpToGraphDdl(dump: string): GraphDdl {
  const counts: GraphDdl['counts'] = { table: 0, view: 0, function: 0, fk: 0, trigger: 0, external: 0 };
  const tables: string[] = [];
  const rest: string[] = [];
  const external = new Set<string>();

  const blocks = dump.split(/\n--\n-- Name: [^\n]*\n--\n/).slice(1);
  for (const raw of blocks) {
    const block = raw.trim();

    const table = block.match(new RegExp(`^CREATE (?:UNLOGGED )?TABLE public\\.(${IDENT}) \\(`));
    if (table) {
      tables.push(`CREATE TABLE ${bare(table[1])} (id INT);`);
      counts.table++;
      continue;
    }

    const view = block.match(
      new RegExp(`^CREATE (?:MATERIALIZED )?VIEW public\\.(${IDENT})(?: WITH \\([^)]*\\))? AS\\s+([\\s\\S]*?);?\\s*$`),
    );
    if (view) {
      const body = view[2].replace(/\s+WITH (?:NO )?DATA\s*$/i, '').replace(/;\s*$/, '');
      rest.push(`CREATE VIEW ${bare(view[1])} AS ${bare(body)};`);
      counts.view++;
      continue;
    }

    const fn = block.match(new RegExp(`^CREATE FUNCTION public\\.(${IDENT})\\([\\s\\S]*?AS (\\$\\w*\\$)([\\s\\S]*?)\\2`));
    if (fn) {
      rest.push(`CREATE FUNCTION ${bare(fn[1])}() RETURNS void AS $gfx$ ${bare(fn[3])} $gfx$ LANGUAGE plpgsql;`);
      counts.function++;
      continue;
    }

    const fk = block.match(
      new RegExp(
        `^ALTER TABLE ONLY public\\.(${IDENT})\\s+ADD CONSTRAINT (${IDENT}) FOREIGN KEY \\(([^)]*)\\) REFERENCES (\\w+)\\.(${IDENT})\\(([^)]*)\\)`,
      ),
    );
    if (fk) {
      const target = qualified(fk[4], fk[5]);
      if (fk[4] !== 'public') external.add(target);
      rest.push(
        `ALTER TABLE ${bare(fk[1])} ADD CONSTRAINT ${bare(fk[2])} FOREIGN KEY (${bare(fk[3])}) REFERENCES ${target}(${bare(fk[6])});`,
      );
      counts.fk++;
      continue;
    }

    const trigger = block.match(
      new RegExp(`^CREATE (?:CONSTRAINT )?TRIGGER (${IDENT}) [\\s\\S]*? ON public\\.(${IDENT}) [\\s\\S]*?EXECUTE (?:FUNCTION|PROCEDURE) (\\w+)\\.(${IDENT})\\(`),
    );
    if (trigger) {
      rest.push(
        `CREATE TRIGGER ${bare(trigger[1])} AFTER INSERT ON ${bare(trigger[2])} FOR EACH ROW EXECUTE FUNCTION ${qualified(trigger[3], trigger[4])}();`,
      );
      counts.trigger++;
    }
  }

  // Stub nodes for FK targets outside public (auth.users) so those edges resolve.
  const stubs = [...external].sort().map((name) => `CREATE TABLE ${name} (id INT);`);
  counts.external = stubs.length;

  const header = '-- Generated by scripts/db/graphify-schema.ts from pg_dump --schema-only. Do not edit.';
  return { ddl: [header, ...tables, ...stubs, ...rest].join('\n') + '\n', counts };
}

function dumpLiveSchema(): string {
  const url = process.env.POSTGRES_URL_NON_POOLING;
  if (!url) throw new Error('POSTGRES_URL_NON_POOLING is not set; pass --dump <file> instead.');
  const cleanUrl = url.replace(/[?&]supa=[^&]*/, '');
  return execFileSync(
    process.env.PG_DUMP || 'pg_dump',
    [cleanUrl, '--schema-only', '--no-owner', '--no-privileges', '--schema=public'],
    {
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
      env: { ...process.env, PGOPTIONS: '-c default_transaction_read_only=on' },
    },
  );
}

function main(): void {
  const dumpFlag = process.argv.indexOf('--dump');
  const dump = dumpFlag > -1 ? fs.readFileSync(process.argv[dumpFlag + 1], 'utf8') : dumpLiveSchema();
  const { ddl, counts } = convertDumpToGraphDdl(dump);
  if (counts.table === 0) throw new Error('No CREATE TABLE found in the dump; refusing to write an empty schema.');
  fs.mkdirSync(path.dirname(GRAPH_SCHEMA_PATH), { recursive: true });
  fs.writeFileSync(GRAPH_SCHEMA_PATH, ddl);
  console.log(`Wrote ${GRAPH_SCHEMA_PATH}`, counts);
}

if (require.main === module) main();
