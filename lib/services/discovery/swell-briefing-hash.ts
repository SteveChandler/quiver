import { createHash } from "node:crypto";

/**
 * Canonical JSON shared with the local worker, which hashes with Python's
 * `json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
 * allow_nan=False)`. Both sides must produce byte-identical output or every
 * upload fails revalidation, so the rules are spelled out rather than inherited
 * from `JSON.stringify`:
 *
 * - object keys sorted by code point, which is what Python's `sort_keys` does
 * - no whitespace between tokens
 * - literal Unicode rather than \\u escapes (`ensure_ascii=False`)
 * - NaN and Infinity rejected (`allow_nan=False`) instead of silently nulled
 * - `undefined` and functions rejected, since Python has no equivalent and
 *   `JSON.stringify` would drop the key and change the hash
 *
 * Numbers are the subtle one. Python prints floats with `repr`, so an integral
 * float is `2.0` where JavaScript writes `2`. Values that arrive over the wire
 * as JSON always parse back to Python ints for integral values, so the two
 * agree; `swell-briefing-hash.test.ts` pins that against a fixture generated by
 * the worker's own `canonical()`.
 */
export function canonicalJson(value: unknown): string {
  return encode(value, new WeakSet<object>());
}

function encode(value: unknown, seen: WeakSet<object>): string {
  if (value === null) return "null";

  switch (typeof value) {
    case "boolean":
      return value ? "true" : "false";
    case "number":
      if (!Number.isFinite(value)) {
        throw new Error("canonicalJson: NaN and Infinity are not representable");
      }
      // `Object.is` separates -0 from 0; Python writes `-0.0`, so refuse rather
      // than emit a byte sequence the worker cannot reproduce.
      if (Object.is(value, -0)) {
        throw new Error("canonicalJson: negative zero is not representable");
      }
      return String(value);
    case "string":
      return encodeString(value);
    case "object":
      break;
    default:
      throw new Error(`canonicalJson: ${typeof value} is not representable`);
  }

  const object = value as object;
  if (seen.has(object)) throw new Error("canonicalJson: circular reference");
  seen.add(object);
  try {
    if (Array.isArray(object)) {
      return `[${object.map((item) => encode(item, seen)).join(",")}]`;
    }
    const entries = Object.entries(object as Record<string, unknown>)
      .filter(([, item]) => item !== undefined)
      .sort(([a], [b]) => compareCodePoints(a, b));
    const body = entries
      .map(([key, item]) => `${encodeString(key)}:${encode(item, seen)}`)
      .join(",");
    return `{${body}}`;
  } finally {
    seen.delete(object);
  }
}

/**
 * Python sorts by code point. JavaScript's default comparator comparares UTF-16
 * code units, which orders characters outside the basic plane differently, so
 * compare the code points directly.
 */
function compareCodePoints(a: string, b: string): number {
  const left = [...a];
  const right = [...b];
  for (let i = 0; i < Math.min(left.length, right.length); i += 1) {
    const difference = left[i].codePointAt(0)! - right[i].codePointAt(0)!;
    if (difference !== 0) return difference;
  }
  return left.length - right.length;
}

const ESCAPES: Record<string, string> = {
  '"': '\\"',
  "\\": "\\\\",
  "\n": "\\n",
  "\r": "\\r",
  "\t": "\\t",
  "\b": "\\b",
  "\f": "\\f",
};

/** Matches Python's `ensure_ascii=False`: escape only what JSON requires. */
function encodeString(value: string): string {
  let out = '"';
  for (const character of value) {
    const escape = ESCAPES[character];
    if (escape !== undefined) {
      out += escape;
      continue;
    }
    const code = character.codePointAt(0)!;
    out += code < 0x20 ? `\\u${code.toString(16).padStart(4, "0")}` : character;
  }
  return `${out}"`;
}

export function sha256Hex(value: string): string {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

/** SHA-256 over the canonical snapshot with `inputHash` removed. */
export function briefingInputHash(snapshot: Record<string, unknown>): string {
  return hashWithout(snapshot, "inputHash");
}

/** SHA-256 over the canonical artifact with `artifactId` removed. */
export function briefingArtifactId(artifact: Record<string, unknown>): string {
  return hashWithout(artifact, "artifactId");
}

function hashWithout(body: Record<string, unknown>, omit: string): string {
  const rest: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(body)) {
    if (key !== omit) rest[key] = value;
  }
  return sha256Hex(canonicalJson(rest));
}
